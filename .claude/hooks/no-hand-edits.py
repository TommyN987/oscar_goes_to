#!/usr/bin/env python3
"""PreToolUse hook for Edit and Write: denies edits to files that are never changed by hand.

- Generated files are regenerated by a command.
- Lockfiles change only through their package manager.
- A migration already on main has been applied in production, and sqlx refuses to start if it changes.
- `.env` holds Tommy's secrets.
"""

import json
import os
import subprocess
import sys

GENERATED = {
    "openapi.json": "It is generated from the handlers. Change the handler, then run `just generate`.",
    "frontend/src/lib/api/schema.d.ts": "It is generated from openapi.json. Run `just generate`.",
}
LOCKFILES = {
    "Cargo.lock": "Change a Cargo.toml and let cargo update the lockfile.",
    "frontend/pnpm-lock.yaml": "Change frontend/package.json and let pnpm update the lockfile.",
}
MIGRATIONS_DIR = "crates/adapters/migrations/"


def is_on_main(project_dir, path):
    """Whether origin/main already holds this file."""
    return (
        subprocess.run(
            ["git", "-C", project_dir, "cat-file", "-e", f"origin/main:{path}"],
            capture_output=True,
        ).returncode
        == 0
    )


def reason_to_deny(project_dir, path):
    if path in GENERATED:
        return GENERATED[path]
    if path in LOCKFILES:
        return LOCKFILES[path]
    if path == ".env":
        return "It holds Tommy's secrets. Tell him which line to add or change."
    if path.startswith(MIGRATIONS_DIR) and path.endswith(".sql") and is_on_main(project_dir, path):
        return (
            "This migration is on main, so it has been applied, and sqlx refuses to start on a changed checksum. "
            "Add a new migration instead."
        )
    return None


def main():
    hook_input = json.load(sys.stdin)
    project_dir = os.environ.get("CLAUDE_PROJECT_DIR") or hook_input.get("cwd") or os.getcwd()
    file_path = hook_input.get("tool_input", {}).get("file_path", "")
    if not file_path:
        return
    path = os.path.relpath(os.path.realpath(file_path), os.path.realpath(project_dir))

    reason = reason_to_deny(project_dir, path)
    if reason:
        json.dump(
            {
                "hookSpecificOutput": {
                    "hookEventName": "PreToolUse",
                    "permissionDecision": "deny",
                    "permissionDecisionReason": f"`{path}` is never edited by hand. {reason}",
                }
            },
            sys.stdout,
        )


if __name__ == "__main__":
    main()
